class ChatSection(QWidget):
    def __init__(self):
        super(ChatSection, self).__init__()
        self.old_chat_message = ""
        
        layout = QVBoxLayout(self)
        layout.setContentsMargins(10, 10, 10, 10)
        layout.setSpacing(5)
        
        self.chat_text_edit = QTextEdit()
        self.chat_text_edit.setReadOnly(True)
        self.chat_text_edit.setFrameStyle(QFrame.NoFrame)
        self.chat_text_edit.setStyleSheet("background-color: black; color: white;")
        layout.addWidget(self.chat_text_edit)
        
        self.gif_label = QLabel()
        self.gif_label.setStyleSheet("border: none;")
        movie = QMovie(GraphicsDirectoryPath('Jarvis.gif'))
        movie.setScaledSize(QSize(480, 270))
        self.gif_label.setAlignment(Qt.AlignRight | Qt.AlignBottom)
        self.gif_label.setMovie(movie)
        movie.start()
        layout.addWidget(self.gif_label)
        
        self.label = QLabel("")
        self.label.setStyleSheet("color: white; font-size: 10px; margin-right: 195px; border: None;")
        self.label.setAlignment(Qt.AlignRight)
        layout.addWidget(self.label)
        
        self.chat_text_edit.setFont(QFont("Arial", 13))
        
        self.timer = QTimer(self)
        self.timer.timeout.connect(self.loadMessages)
        self.timer.timeout.connect(self.SpeechRecogText)
        self.timer.start(1000)  # Updated timer interval to 1000ms (1 second)
        
    def loadMessages(self):
        try:
            file_path = TempDirectoryPath('Status.data')
            if os.path.exists(file_path):
                with open(file_path, "r", encoding='utf-8') as file:
                    messages = file.read().strip()
                    
                    if messages and messages != self.old_chat_message:
                        self.chat_text_edit.setPlainText(messages)  # Overwrites the text instead of appending
                        self.old_chat_message = messages
                        self.chat_text_edit.repaint()  # Forces UI update
        except Exception as e:
            print(f"Error loading messages: {e}")

    def SpeechRecogText(self):
        try:
            file_path = TempDirectoryPath('Status.data')
            if os.path.exists(file_path):
                with open(file_path, "r", encoding='utf-8') as file:
                    messages = file.read().strip()
                    self.label.setText(messages)
        except Exception as e:
            print(f"Error updating label: {e}")

    def load_icon(self, path, width=60, height=60):
        pixmap = QPixmap(path)
        new_pixmap = pixmap.scaled(width, height)
        self.icon_label.setPixmap(new_pixmap)

    def toggle_icon(self, event=None):
        if self.toggled:
            self.load_icon(GraphicsDirectoryPath('voice.png'), 60, 60)
            MicButtonInitialized()
        else:
            self.load_icon(GraphicsDirectoryPath('mic.png'), 60, 60)
            MicButtonClosed()

        self.toggled = not self.toggled

    def addMessage(self, message, color):
        cursor = self.chat_text_edit.textCursor()
        format = QTextCharFormat()
        formatm = QTextBlockFormat()
        formatm.setTopMargin(10)
        formatm.setLeftMargin(10)
        format.setForeground(QColor(color))
        cursor.setCharFormat(format)
        cursor.setBlockFormat(formatm)
        cursor.insertText(message + "\n")
        self.chat_text_edit.setTextCursor(cursor)

